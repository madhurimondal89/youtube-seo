import { KeywordResearchResponse, VideoAuditResult } from "./types";

export function exportToJSON(data: any, filename: string) {
  const blob = new Blob([JSON.stringify(data, null, 2)], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${filename}.json`;
  a.click();
  URL.revokeObjectURL(url);
}

export function exportKeywordsToCSV(response: KeywordResearchResponse, filename: string) {
  const headers = [
    "Keyword",
    "Opportunity Score",
    "Estimated Competition",
    "Relative Demand",
    "Word Count",
    "Intents",
    "Search Surface",
    "Data Provenance",
  ];

  const rows = response.keywords.map((k) => [
    `"${k.keyword.replace(/"/g, '""')}"`,
    k.opportunity_score,
    k.estimated_competition,
    k.relative_demand,
    k.word_count,
    `"${k.intents.join(", ")}"`,
    `"${k.search_surface}"`,
    k.provenance,
  ]);

  const csvContent = [headers.join(","), ...rows.map((r) => r.join(","))].join("\n");
  const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${filename}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

export function exportToMarkdown(response: KeywordResearchResponse, filename: string) {
  const dateStr = new Date().toISOString();
  let md = `# YouTube SEO — Research Report: "${response.seed}"\n\n`;
  md += `**Generated**: ${dateStr}\n`;
  md += `**Data Provenance**: ${response.data_provenance} (Public & Statistical Derivation)\n`;
  md += `**Total Keywords Found**: ${response.total_found}\n`;
  md += `**Execution Latency**: ${response.execution_time_ms}ms\n\n`;

  md += `## Top High-Opportunity Keywords\n\n`;
  md += `| Keyword | Opportunity | Competition | Relative Demand | Intents |\n`;
  md += `|---|---|---|---|---|\n`;
  for (const k of response.keywords.slice(0, 15)) {
    md += `| ${k.keyword} | **${k.opportunity_score}/100** | ${k.estimated_competition}/100 | ${k.relative_demand}/100 | ${k.intents.join(", ")} |\n`;
  }

  if (response.clusters.length > 0) {
    md += `\n## Recommended Topic Clusters & Content Pillars\n\n`;
    for (const c of response.clusters) {
      md += `### 📁 ${c.cluster_name} (Avg Opp: ${c.avg_opportunity_score}/100)\n`;
      md += `- **Pillar Video**: ${c.recommended_pillar_title}\n`;
      md += `- **Playlist**: ${c.playlist_suggestion}\n`;
      md += `- **Supporting Ideas**:\n`;
      for (const idea of c.supporting_video_ideas) {
        md += `  - ${idea}\n`;
      }
      md += `\n`;
    }
  }

  md += `\n---\n*Report generated by YouTube SEO — Independent Self-Hosted YouTube Creator Intelligence Platform.*\n`;

  const blob = new Blob([md], { type: "text/markdown;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${filename}.md`;
  a.click();
  URL.revokeObjectURL(url);
}
